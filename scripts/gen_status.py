def use_project(root: Path) -> None:
    """Point the module at a project. `F3-T2`.

    The paths are module state rather than a parameter threaded through fifteen
    functions: the smaller diff is the one whose eleven existing tests still mean what
    they meant. Every path is derived here, so there is one place to be wrong.
    """
    global ROOT, REGISTER, STATUS, SPEC, PLANS
    ROOT = Path(root).resolve()
    REGISTER = ROOT / "docs" / "plans" / "00-register.md"
    STATUS = ROOT / "docs" / "plans" / "00-status.md"
    SPEC = ROOT / "docs" / "specs" / "SPEC.md"
    PLANS = ROOT / "docs" / "plans"


def in_scope() -> list[Path]:
    """Projects the compliance checker considers in scope — it already reads the
    register's Scope table, so exclusions are honoured without a second list."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("cc", HOME / "scripts" / "check_compliance.py")
    cc = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(cc)
    excl, newest = cc.excluded(), ""
    found = cc.projects([])
    dates = [d for d in (cc.last_commit(p) for p in found) if d]
    newest = max(dates) if dates else ""
    return [p for p in found
            if not cc.check(p, cc.required_documents(), cc.sha(cc.upstream_body()),
                            {}, newest, excl)["dormant"]]

BANNER = "<!-- GENERATED by scripts/gen_status.py — do not edit by hand. -->"

# Axis 2 of conventions.md, in the order that file lists them.  A register with no rows
# still gets a line: "Mutations 0" is a fact, and an absent row would read as an oversight.
REGISTERS = [("D", "Decisions"), ("RR", "Risks"), ("O", "Owner items"),
             ("A", "Agent items"), ("H", "Hooks"), ("M", "Mutations")]
# Named when present, "Other (X)" otherwise.
EXTRA_NAMES = {"C": "Chores", "G": "Gates"}

# Longest first: "not built" must win over "built".
STATUS_WORDS = ["not built", "superseded", "proposed", "ratified", "rejected",
                "resolved", "closed", "built", "held", "open", "done", "unknown",
                "survived", "killed"]
# `RR38`.  A mutation's states are `killed` and `survived`, and the polarity is the point:
# `conventions.md` defines `M<n>` as a named way to break the code paired with the test
# that must catch it, so **killed is the satisfied state** and a **survivor is a finding**
# — a break nothing caught.  Neither word was known, both fell through to an inferred
# status, and ten killed mutations were reported as ten open items: a fully covered module
# reading as entirely outstanding.
# `held` is parked, not finished, so it counts open. `resolved` counts closed.
OPEN_STATES = {"open", "proposed", "not built", "survived", "held"}

# `unknown` is a third answer and it is deliberately in neither set.  `RR37`: a register
# that writes `unknown` is saying *the source said nothing about status — this is a
# question for the owner, not a guess*, and the generator used to answer it `open` by
# falling through to a status inferred from scanning the row.  Four of five rows counted
# open under "Other (C)" in `home-assistant` were unknowns.  Rendering it `closed` would
# be the same error pointing the other way.
UNKNOWN_STATES = {"unknown"}

# Who owns an open row when its table has no Owner column.  Taken from the register's own
# prose, not from judgement: Owner items are "outstanding items only the owner can close",
# and the one open decision is marked "Awaiting the owner".  Every other register is left
# unassigned rather than guessed — an unowned open item is a real finding, and inventing
# an owner would hide it.
OWNER_BY_REGISTER = {"O": "owner", "D": "owner"}

_SPLIT = re.compile(r"(?<!\\)\|")                   # a `\|` inside a cell is not a column break
_UNIT = re.compile(r"^[FC]\d+[a-z]?$")
_SCOPE = re.compile(r"^[a-z]+\(([^)]+)\):")
_TASK = re.compile(r"^#{2,4}\s+((?:F|C)\d+[a-z]?-T\d+)\b", re.M)
# A plan header packs several fields onto one line, separated by `·`.  Stop at the
# separator AND at the newline: without the newline a field swallows the rest of the
# document, and the fields below it never match at all.
_FIELD = re.compile(r"\*\*([A-Za-z][A-Za-z ]*?):\*\*\s*([^·\n]*)")


# ---------------------------------------------------------------- register


def rel(p: Path) -> str:
    """A path as the reader knows it.  Repo-relative where it can be, whole otherwise —
    never an exception, because the one place this is called is the code that reports a
    failure, and a reporter that crashes turns a stale file into a stack trace."""
    try:
        return p.relative_to(ROOT).as_posix()
    except ValueError:
        return p.as_posix()


def project_name() -> str:
    """The name the register gives itself (`# Register — <name>`), else the folder name.

    Not the folder alone: CI checks this repo out as `code-process-review`, so a title
    from the folder made `--check` fail on GitHub and pass locally.
    """
    first = REGISTER.read_text(encoding="utf-8").split("\n", 1)[0] if REGISTER.is_file() else ""
    m = re.match(r"#\s+Register\s+—\s+(.+?)\s*$", first)
    return m.group(1) if m else ROOT.name


def prefix(item_id: str) -> str:
    if "-M" in item_id:                  # F8-M1 is a mutation, not a feature
        return "M"
    m = re.match(r"[A-Z]+", item_id)
    return m.group(0) if m else "?"


def norm_status(cell: str) -> str:
    s = re.sub(r"[*~`]", "", cell).strip().lower()
    return next((w for w in STATUS_WORDS if s.startswith(w)), "")


def columns(path: Path) -> dict[str, dict[str, str]]:
    """id -> {column heading: raw cell}, for the columns `Item` does not model.

    Header-driven so a table can gain a column without this script guessing by position.
    """
    out: dict[str, dict[str, str]] = {}
    heads: list[str] = []
    fenced = False
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if register._FENCE.match(line):
            fenced = not fenced
            continue
        if fenced:
            continue
        if stripped.startswith("##"):
            heads = []
            continue
        if stripped.startswith("| ID ") or stripped.startswith("|ID|"):
            heads = [c.strip() for c in _SPLIT.split(stripped.strip("|"))]
            continue
        m = register._ROW.match(line)
        if not m or not heads:
            continue
        cells = [c.strip() for c in _SPLIT.split(m.group("rest"))]
        out.setdefault(m.group("key"), dict(zip(heads[1:], cells)))
    return out


def status_of(item, cols: dict[str, str]) -> str:
    """The Status column wins over `Item.status` where a table has one.

    Not a second parser, a narrower one.  `Item.status` is inferred by scanning every
    cell for a status word, which misreads a row whose *text* contains one: `O5` says
    "one closed and one open" and comes back `closed` while its Status column reads
    `open`.  Reading the named column cannot make that mistake.
    """
    return norm_status(cols.get("Status", "")) or item.status


def is_open(status: str) -> bool:
    return status in OPEN_STATES


# ---------------------------------------------------------------- plans and git


def plan_units() -> dict[str, dict]:
    """Structural units that have a plan file, with the header fields it declares."""
    units: dict[str, dict] = {}
    for path in sorted(PLANS.glob("*.md")):
        if not _UNIT.match(path.stem):
            continue
        text = path.read_text(encoding="utf-8")
        head = "\n".join(text.splitlines()[:15])
        fields = {k.strip(): v.strip() for k, v in _FIELD.findall(head)}
        status = fields.get("Status", "")
        units[path.stem] = {
            "status": status.split(". ")[0].rstrip(".") or "—",
            "milestone": fields.get("Milestone", "") or "—",
            "priority": fields.get("Priority", "") or "—",
            "owner": fields.get("Owner", "") or "—",
            "plan": rel(path),
            "tasks": sorted(set(_TASK.findall(text))),
        }
    return units


def git(*args: str) -> str:
    try:
        r = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)
    except OSError:
        return ""
    return r.stdout if r.returncode == 0 else ""


def git_units() -> dict[str, set[str]]:
    """unit -> the task IDs of that unit seen in a commit scope.

    Deliberately a set, never a count: a commit count would change on every commit and
    make this page stale by the act of committing it.
    """
    seen: dict[str, set[str]] = {}
    for subject in git("log", "--format=%s").splitlines():
        m = _SCOPE.match(subject.strip())
        if not m:
            continue
        for raw in m.group(1).split(","):
            ident = raw.strip()
            unit = ident.split("-")[0]
            if _UNIT.match(unit):
                seen.setdefault(unit, set())
                if ident != unit:
                    seen[unit].add(ident)
    return seen


def vision() -> str:
    if not SPEC.is_file():
        return (f"`{rel(SPEC)}` is **missing**. Nothing in this "
                f"repository states, in one sentence, what it is for — and that sentence "
                f"is the one thing here no script can check.")
    for line in SPEC.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            return line
    return f"`{rel(SPEC)}` is present but states no vision sentence."


# ---------------------------------------------------------------- rendering


def table(heads: list[str], rows: list[list[str]]) -> list[str]:
    def cell(x: str) -> str:
        return str(x).replace("|", r"\|").replace("\n", " ").strip() or "—"
    out = ["| " + " | ".join(heads) + " |",
           "|" + "|".join("---" for _ in heads) + "|"]
    out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return out


def render() -> str:
    # An ID in two tables (ZenPom's owner-fields overlay) is one item: first row wins.
    # Duplicates inside one register are H5's to report, not this page's to count twice.
    seen: set[str] = set()
    items = [i for i in parse(REGISTER) if not (i.id in seen or seen.add(i.id))]
    cols = columns(REGISTER)
    state = {i.id: status_of(i, cols.get(i.id, {})) for i in items}
    plans = plan_units()

    L: list[str] = [
        BANNER,
        "<!-- Regenerate: python3 scripts/gen_status.py   ·   CI: python3 scripts/gen_status.py --check -->",
        "",
        # ROOT, not HOME: the project being rendered names its own page.  Deriving
        # from HOME titled all 13 projects "Status — turing-review" in one run, and
        # H1 passed on every one of them, because a page matching what the generator
        # produces is consistent and not necessarily correct (`RR44`).
        f"# Status — {project_name()}",
        "",
        f"Generated from `{rel(REGISTER)}`, the plan files in "
        f"`docs/plans/` and `{rel(SPEC)}`, by "
        "`scripts/gen_status.py`. Hand edits are reverted by the next run and fail CI "
        "in the meantime (`D13`, `H1`).",
        "",
        "**Nothing on this page comes from git, and there is no date.** A generated file "
        "that embeds anything which moves on its own can never compare equal to a "
        "regeneration of itself. This page once reported which task IDs had appeared in a "
        "commit scope, so the commit that first shipped `F3-T1` was the thing that made "
        "`F3-T1` appear — the page was stale by the act of committing it, and one project "
        "collected five regeneration commits in a day, none of which carried information "
        "(`RR11`). Everything here is derived from the register, so it changes only when "
        "the register changes, and regenerating is part of that same edit.",
        "",
        "## The vision sentence",
        "",
        f"> {vision()}",
        "",
        "## Milestone",
        "",
        "Named, never numbered (`D2`). **No source read here marks a milestone as the "
        "current one** — neither the register nor any plan header says which release is "
        "in flight, so this page does not claim to know.",
        "",
    ]

    ms_dec = Counter(cols.get(i.id, {}).get("Milestone", "").strip()
                     for i in items if prefix(i.id) == "D")
    ms_dec.pop("", None)
    ms_dec.pop("—", None)
    ms_plan: dict[str, list[str]] = {}
    for uid, u in plans.items():
        ms_plan.setdefault(u["milestone"], []).append(uid)
    rows = [[m, str(ms_dec.get(m, 0)), ", ".join(sorted(ms_plan.get(m, [])))]
            for m in sorted(set(ms_dec) | set(ms_plan))]
    L += table(["Milestone", "Decisions landing here", "Units"], rows)

    # ---- features and chores
    L += ["", "## Features and chores", "",
          "Status is what the unit's own plan header declares. What has landed in git is "
          "deliberately not here — see the note above.", ""]
    rows = []
    for uid in sorted(plans, key=lambda u: (u[0], int(re.sub(r"\D", "", u) or 0), u)):
        u = plans[uid]
        kind = "feature" if uid.startswith("F") else "chore"
        rows.append([uid, kind, u["status"], u["milestone"], u["priority"], u["owner"],
                     f"`{u['plan']}`", f"{len(u['tasks'])} planned"])
    L += table(["ID", "Kind", "Status", "Milestone", "P", "Owner", "Plan", "Tasks"], rows)

    # ---- register counts
    L += ["", "## Registers", "",
          "Counted from the register itself. A register with no rows still gets a line.", ""]
    by_prefix: dict[str, list] = {}
    for i in items:
        by_prefix.setdefault(prefix(i.id), []).append(i)
    known = [p for p, _ in REGISTERS]
    order = REGISTERS + [(p, EXTRA_NAMES.get(p, f"Other ({p})"))
                         for p in sorted(by_prefix) if p not in known]
    rows = []
    for p, name in order:
        group = by_prefix.get(p, [])
        opened = [i for i in group if is_open(state[i.id])]
        unsure = [i for i in group if state[i.id] in UNKNOWN_STATES]
        rows.append([f"{name} (`{p}`)", str(len(group)), str(len(opened)),
                     str(len(unsure)), str(len(group) - len(opened) - len(unsure))])
    L += table(["Register", "Rows", "Open", "Unknown", "Closed"], rows)
    if any(r[3] != "0" for r in rows):
        L += ["", "`Unknown` is not a third kind of open. It means the source document said "
              "nothing about status, so the page will not guess — the row is a question for "
              "the owner (`RR37`).", ""]

    L += ["", "### By status", ""]
    rows = []
    for p, name in order:
        counts = Counter(state[i.id] for i in by_prefix.get(p, []))
        for st in sorted(counts):
            rows.append([f"`{p}`", st, str(counts[st])])
    L += table(["Register", "Status", "Count"], rows)

    # ---- hooks
    hooks = [i for i in items if prefix(i.id) == "H"]
    built = [i for i in hooks if state[i.id] in ("built", "closed")]
    L += ["", "## Hooks", "",
          f"**{len(built)} of {len(hooks)} built.** Prose is advisory; hooks are not. "
          "A hook's status is what the register says — this page does not go looking in "
          "`scripts/` for a file and infer that the hook works, because a file existing "
          "is not evidence that it ever failed.", ""]
    rows = [[i.id, i.title, cols.get(i.id, {}).get("Surface", ""),
             cols.get(i.id, {}).get("Protects", ""), state[i.id]] for i in hooks]
    L += table(["ID", "Hook", "Surface", "Protects", "Status"], rows)

    # ---- open work
    L += ["", "## Open, and owned by whom", "",
          "Every open row in the register. Owner is the row's Owner column where the table "
          "has one; otherwise it is `owner` for the two registers whose own text says only "
          "the owner can close them, and `unassigned` everywhere else — an open item nobody "
          "owns is a finding, not something to paper over with a default.", ""]
    rows = []
    for i in items:
        st = state[i.id]
        if not is_open(st) and st not in UNKNOWN_STATES:
            continue
        c = cols.get(i.id, {})
        owner = c.get("Owner", "").strip() or OWNER_BY_REGISTER.get(prefix(i.id), "unassigned")
        prio = c.get("P", "").strip() or i.priority or "—"
        title = i.title
        if prefix(i.id) == "D":                     # the D table's text column is `Decision`
            title = register._clean(c.get("Decision", "")) or title
        # register._clean truncates at 120 characters.  Say so, rather than ending a
        # sentence mid-word and letting a reader take the fragment for the whole item.
        rows.append([owner, i.id, prio, st, title + "…" if len(title) >= 120 else title])
    rows.sort(key=lambda r: (r[0].lower(), r[1][0], int(re.sub(r"\D", "", r[1]) or 0)))
    L += table(["Owner", "ID", "P", "Status", "Item"], rows)

    L += ["", "---", "", f"{len(rows)} open register rows.", ""]
    return "\n".join(L)


# ---------------------------------------------------------------- cli


def diff(expected: str, actual: str) -> str:
    return "".join(difflib.unified_diff(
        actual.splitlines(keepends=True), expected.splitlines(keepends=True),
        fromfile=f"{rel(STATUS)} (on disk)",
        tofile=f"{rel(STATUS)} (regenerated)"))


def one(argv: list[str]) -> int:
    expected = render()
    if "--print" in argv:
        print(expected)
        return 0
    if "--check" in argv:
        actual = STATUS.read_text(encoding="utf-8") if STATUS.is_file() else ""
        if actual == expected:
            print(f"H1 pass — {rel(STATUS)} is what the register says it should be")
            return 0
        print(f"\nH1 FAIL — {rel(STATUS)} is "
              f"{'missing' if not actual else 'stale or hand-edited'}.\n")
        print(diff(expected, actual) or "  (file missing — nothing to diff)")
        print("\n  Fix: python3 scripts/gen_status.py\n")
        return 1
    STATUS.parent.mkdir(parents=True, exist_ok=True)
    STATUS.write_text(expected, encoding="utf-8")
    print(f"wrote {rel(STATUS)} ({len(expected.splitlines())} lines)")
    return 0


def main(argv: list[str]) -> int:
    """`gen_status.py [project] [--check|--print] [--all]`

    `--all` renders every in-scope project. `RR19`: twelve generated pages become twelve
    ways to go stale, because none of those projects run CI. This repo does — so
    `--all --check` from here is what keeps the corpus honest, rather than twelve
    workflows nobody will add.
    """
    # Take flags from the whole vector, not argv[1:]. The entry point once passed
    # sys.argv[1:] while this sliced again, and --all was silently eaten: the command
    # reported on one project and looked like it had checked twelve.
    args = [a for a in argv if not a.endswith("gen_status.py")]
    flags = [a for a in args if a.startswith("-")]
    named = [a for a in args if not a.startswith("-")]

    if "--all" in flags:
        rest = [argv[0]] + [f for f in flags if f != "--all"]
        bad, done, skipped = [], 0, []
        for proj in in_scope():
            use_project(proj)
            if not REGISTER.is_file():
                skipped.append(proj.name)
                continue
            print(f"— {proj.name}")
            own = proj / "scripts" / "gen_status.py"
            if own.is_file():
                # The project writes its own page (ZenTomato). Check with ITS generator;
                # never write over it from here.
                if "--check" not in rest:
                    print("  has its own generator — left alone")
                    continue
                done += 1
                r = subprocess.run([sys.executable, str(own), "--check"], cwd=proj,
                                   capture_output=True, text=True)
                print("  " + ((r.stdout + r.stderr).strip().splitlines() or ["(no output)"])[-1])
                if r.returncode != 0:
                    bad.append(proj.name)
                continue
            done += 1
            if one(rest) != 0:
                bad.append(proj.name)
        if skipped:
            print(f"  no register yet ({len(skipped)}): {', '.join(skipped)}")
        if bad:
            print(f"\nH1 FAIL — stale in: {', '.join(bad)}")
            return 1
        # Checking nothing is not the same as finding nothing wrong. Two other hooks
        # here printed a pass message over zero files before that was fixed; this is
        # the same shape and it does not get to make the same claim.
        if not done:
            print(f"\nH1 — no project has a register yet, so nothing was checked. "
                  f"Not a pass.")
            return 0
        print(f"\nH1 pass — {done} project status page(s) current, {len(skipped)} without "
              f"a register yet")
        return 0

    if named:
        use_project(Path(named[0]))
    return one([argv[0]] + flags)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
