"""H1 — writes `docs/plans/00-status.md` from the register, and checks it (`D13`).

    python3 scripts/gen_status.py [project] [--check | --print] [--all]

`--check` rebuilds the page in memory and exits 1 if the file on disk differs.
`--all` does that for every in-scope project.

Rules:
- Nothing on the page comes from git or the clock, so `--check` can pass twice.
- A row whose status is empty or missing is `unknown`, never `open`. The page does
  not guess.
- Rows come from `register.py`. This file reads extra columns but does not parse rows.

Merged 2026-09-24 from this generator and ZenPom's (`D70`). Kept from here: multi-project
runs, strikethrough rows, `**closed** — reason` cells, legend tables. Taken from ZenPom:
unit-scoped mutation IDs (`F8-M1`), code fences ignored, empty status is `unknown`,
`resolved` and `held`, and a table repeating an ID is counted once.
"""
